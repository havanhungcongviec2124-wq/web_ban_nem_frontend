export const getStoredCombos = () => {
  try {
    const raw = localStorage.getItem('nep_combos');
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) return parsed;
    }
  } catch (e) {
    console.error(e);
  }
  return COMBOS;
};

export const saveStoredCombos = (combos) => {
  try {
    localStorage.setItem('nep_combos', JSON.stringify(combos));
    window.dispatchEvent(new Event('nep_combos_updated'));
  } catch (e) {
    console.error(e);
  }
};

